"""Formal Experimental Validation (AZTA-EXP-v1, addendum 1): the experiment matrix, declared before any formal data and before the reserved TEST runs are opened.

    python -B -I rehearsal_tools/exp_matrix.py write      # configs/formal/exp_matrix_v1.json + the shadow session files (exclusive creation; nothing is started)
    python -B -I rehearsal_tools/exp_matrix.py check      # recomputes the matrix and compares it with the committed file (deterministic)

The matrix is a pure function of the frozen route (device widths) and the constants below; it chooses nothing from data. Plans and dev perturbations are generated by the frozen
`core_final_plans.py --retest RUN`, whose seeds derive from the run id. The active (device02) session files are written by `exp_approve.py active` when the owner's Friday approval is
recorded, because they must pin that approval's digests; their scenario is fixed here.

Components (independent unit = one episode: one commanded scenario on one device in one run):
  DETECTION   exp-s01..s25, shadow (no policy change), all ten devices: every device runs a different behavioural anomaly in each session; over a block of 5 sessions every device
              receives every kind once (kind index = (device index + session index) mod 5); 5 blocks = 5 repetitions per kind per device. Addendum 2: jitter is not applicable to
              devices 05-09 (their frozen laws have no jitter fraction), so that slot runs no episode: 225 episodes.
  SCI         exp-s26..s30, shadow: one silence episode and one declared operating-time withdrawal (context), on two different devices per session, rotated over ten devices.
  BENIGN      exp-s31..s35, shadow: no commanded scenario.
  ENFORCEMENT exp-a01..a12, active-authorized, device02 only: 25 behavioural episodes (5 per kind), 5 context and 5 identity (declared revocation) episodes.
Identity episodes need a broker-side revocation, which is itself a policy change, so they exist only in the supervised device02 sessions.
Spares (used only to replace a VOID run, in order, and recorded in the campaign ledger): exp-s36..s40 replace DETECTION or BENIGN runs; exp-s41..s45 replace exp-s26..s30 one to one;
exp-a13 replaces an active session with a context episode, exp-a14 any other active session.
"""
import argparse
import json
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

MATRIX = "configs/formal/exp_matrix_v1.json"
SESSIONS_DIR = "configs/formal/sessions"
FREEZE = "configs/exp_v1/AZTA-EXP-v1_freeze_manifest.json"
FREEZE_SHA256 = "221884e06340cc1a610791ea179c7b522ce8b6633a8442b58d123f115d3b5516"
BASELINE = "3e6c25881bc1846036fa27445001f0a69f39e6dd85bc5e137048a78c03179c7b"
DEVICES = [f"device{n:02d}" for n in range(1, 11)]
KINDS = ("rate", "payload", "burst", "jitter", "drop")
# The catalogue defaults of engineering.attack_control (payload: the 1024-byte setting the pilot sessions used); fixed for every episode.
PARAMS = dict(rate=dict(factor=5), payload=dict(bytes=1024), burst=dict(group=5), jitter=dict(fraction=0.8), drop=dict(probability=0.8))
ONSET_S = {10: 150, 20: 150, 90: 180, 180: 180}            # behavioural onset on the session's coverage clock, by AE window width
DURATION_S = {10: 120, 20: 160, 90: 270, 180: 360}          # at least two full native windows of the device inside the episode
SILENCE = {"device01": 200, "device03": 200, "device05": 200, "device07": 200, "device08": 360}   # longer than the liveness bound 3 x width + 10 s
SCI_PAIRS = [("device01", "device02"), ("device03", "device04"), ("device05", "device06"), ("device07", "device09"), ("device08", "device10")]  # (silence, context)
SCI_ONSET_S, CONTEXT_CUT_S = 150, 300
ACTIVE_CONTEXT_CUT_S = 480
ACTIVE_EPISODE_MAX_S = 110                                  # one anomaly segment; no containment by then = censored
SESSION = dict(clock_session_s=880, max_duration_s=800)
MATRIX_V1_SHA256 = "1fdf21fef57993945466f0eb2e35126ac69c992a960d950e161877300eeb9f09"   # the addendum-1 matrix named by FORMAL_TEST_AUTHORIZATION (in Git history)


def widths():
    from core_runtime import cli
    route = json.loads((ROOT / cli.ROUTE).read_text(encoding="utf-8"))
    return {d: int(r["width_s"]) for d, r in route["devices"].items()}


def active_plan():
    """12 device02 sessions: 25 behavioural episodes (kinds cycled, 5 each), then context (a01-a05) or identity (a06-a10); a11 and a12 behavioural only."""
    sequence = [KINDS[i % 5] for i in range(25)]
    sizes = [2] * 10 + [3, 2]
    runs, i = {}, 0
    for n, size in enumerate(sizes, start=1):
        episodes = [dict(kind=k) for k in sequence[i:i + size]]
        i += size
        if n <= 5:
            episodes.append(dict(kind="context"))
        elif n <= 10:
            episodes.append(dict(kind="identity"))
        runs[f"exp-a{n:02d}"] = dict(mode="active-authorized", component="ENFORCEMENT", device="device02", episodes=episodes,
                                     time_cut_after_s=ACTIVE_CONTEXT_CUT_S if n <= 5 else None)
    assert i == 25 and all(sum(e["kind"] == k for r in runs.values() for e in r["episodes"]) == 5 for k in KINDS + ("context", "identity"))
    return runs


def applicable(device, kind):
    """Addendum 2: a START the device's frozen law can express. Jitter changes a law's jitter fraction; periodic (devices 05-08) and event-gap (device09) laws have none, and the
    frozen live workload refuses it (engineering.fleet_workload.check_command_applicable), so that device stays benign in its jitter slot."""
    from fleet import laws
    return kind != "jitter" or "jitter_fraction" in laws.profile_of(device)


def build():
    w = widths()
    runs = {}
    for block in range(5):
        for j in range(5):
            n = block * 5 + j + 1
            episodes, skipped = [], []
            for i, device in enumerate(DEVICES):
                kind = KINDS[(i + j) % 5]
                if applicable(device, kind):
                    episodes.append(dict(device=device, kind=kind, params=PARAMS[kind], onset_s=ONSET_S[w[device]], duration_s=DURATION_S[w[device]]))
                else:
                    skipped.append(dict(device=device, kind=kind, reason="the device's frozen law has no jitter fraction; the live workload refuses the command (addendum 2)"))
            runs[f"exp-s{n:02d}"] = dict(mode="shadow", component="DETECTION", repetition=block + 1, rotation=j, episodes=episodes, not_applicable=skipped)
    for r, (silent, cut) in enumerate(SCI_PAIRS):
        runs[f"exp-s{26 + r:02d}"] = dict(mode="shadow", component="SCI", repetition=r + 1,
                                          episodes=[dict(device=silent, kind="silence", params={}, onset_s=SCI_ONSET_S, duration_s=SILENCE[silent]),
                                                    dict(device=cut, kind="context", params={}, onset_s=CONTEXT_CUT_S, duration_s=None)],
                                          time_cut_device=cut, time_cut_after_s=CONTEXT_CUT_S)
    for r in range(5):
        runs[f"exp-s{31 + r:02d}"] = dict(mode="shadow", component="BENIGN", repetition=r + 1, episodes=[])
    for n in range(36, 41):
        runs[f"exp-s{n:02d}"] = dict(mode="shadow", component="SPARE", replaces="the next VOID DETECTION or BENIGN run, in ledger order", episodes=None)
    for n in range(41, 46):
        sci = f"exp-s{n - 15:02d}"
        runs[f"exp-s{n:02d}"] = dict(mode="shadow", component="SPARE", replaces=sci, episodes=None, time_cut_device=runs[sci]["time_cut_device"], time_cut_after_s=CONTEXT_CUT_S)
    runs.update(active_plan())
    runs["exp-a13"] = dict(mode="active-authorized", component="SPARE", replaces="a VOID active session that has a context episode", device="device02", episodes=None, time_cut_after_s=ACTIVE_CONTEXT_CUT_S)
    runs["exp-a14"] = dict(mode="active-authorized", component="SPARE", replaces="a VOID active session without a context episode", device="device02", episodes=None, time_cut_after_s=None)
    batches = dict(S1=[f"exp-s{n:02d}" for n in list(range(31, 36)) + list(range(1, 11))] + [f"exp-s{n:02d}" for n in (36, 37, 38)],
                   A=[f"exp-a{n:02d}" for n in range(1, 15)],
                   S2=[f"exp-s{n:02d}" for n in list(range(11, 31)) + [39, 40] + list(range(41, 46))])
    detection = sum(len(s["episodes"]) for s in runs.values() if s["component"] == "DETECTION")
    return dict(schema="azta.formal.experiment_matrix", schema_version=2, release="AZTA-EXP-v1", freeze_manifest=FREEZE, freeze_manifest_sha256=FREEZE_SHA256,
                declared="before any formal data and before the reserved TEST runs are opened (supervisor's condition, 11 November 2026)",
                amended=dict(addendum="docs/final/AZTA_FORMAL_PROTOCOL_ADDENDUM_2.md", supersedes_sha256=MATRIX_V1_SHA256,
                             change="jitter is not applicable to devices 05-09 (no jitter fraction in their frozen laws); those cells run no commanded episode"),
                devices=DEVICES, widths_s=w, kinds=list(KINDS), anomaly_parameters=PARAMS, onset_s_by_width=ONSET_S, duration_s_by_width=DURATION_S,
                active=dict(device="device02", episode_max_s=ACTIVE_EPISODE_MAX_S, context_cut_after_s=ACTIVE_CONTEXT_CUT_S,
                            clicks="the owner's RESTORE after each verified containment, APPROVE ONCE for each context and identity review, RESTORE after each identity quarantine; REJECT any unplanned review"),
                session=dict(SESSION, baseline_policy_sha256=BASELINE, broker="isolated azta-pilot, volume kept, no host port"),
                reserved_test_runs=["g6c-d07", "g5d3a-fx-g6b09", "g5d3a-fx-g6b17"],
                runs=runs, batches=batches,
                counts=dict(detection_episodes=detection, per_kind_per_device=5, per_kind_per_device_scope="every applicable (device, kind) cell", silence=5, context_shadow=5, enforcement_behavioural=25, enforcement_context=5, enforcement_identity=5, benign_sessions=5),
                void_rule="a run is VOID only for these machine-checked causes, never for its results: a failed verification or clock certificate, a launcher, workload or observer failure, "
                          "a failed binding audit, an unapplied scenario command, or (active) a cancelled owner instruction. A VOID run is kept and reported, and replaced once by its spare.",
                stop_rule="the campaign stops (no further run) on any broker policy that is not the baseline digest after a run, any enforcement in a shadow run, a restoration failure, "
                          "a changed protected fingerprint, an unclean tree, or a second consecutive VOID for the same cause.")


def session_file(run_id, spec):
    doc = dict(authorization_ref="FORMAL_EXPERIMENTAL_VALIDATION", baseline_policy_sha256=BASELINE, dev_perturbation=f"configs/dev_perturbations/{run_id}.json", label=run_id,
               plan=f"configs/collection_plans/core_final_{run_id.replace('-', '_')}.json", run_id=run_id, **SESSION)
    if spec.get("time_cut_device"):
        doc.update(time_cut_device=spec["time_cut_device"], time_cut_after_s=spec["time_cut_after_s"])
    return doc


def dump(document):
    return json.dumps(document, indent=1, sort_keys=True) + "\n"


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("command", choices=("write", "check", "amend-2"))
    args = parser.parse_args(argv)
    matrix = build()
    if args.command == "amend-2":                    # replaces ONLY the exact addendum-1 matrix; the shadow session files do not depend on the episodes and must be unchanged
        import hashlib
        if hashlib.sha256((ROOT / MATRIX).read_bytes()).hexdigest() != MATRIX_V1_SHA256:
            raise SystemExit("REFUSED: the committed matrix is not the addendum-1 matrix")
        if not all((ROOT / SESSIONS_DIR / f"{r}.json").read_bytes() == dump(session_file(r, s)).encode("utf-8") for r, s in matrix["runs"].items() if s["mode"] == "shadow"):
            raise SystemExit("REFUSED: a shadow session file would change")
        (ROOT / MATRIX).write_bytes(dump(matrix).encode("utf-8"))
        print(json.dumps(dict(amended=MATRIX, detection_episodes=matrix["counts"]["detection_episodes"]), indent=1))
        return 0
    if args.command == "check":
        same = (ROOT / MATRIX).read_bytes() == dump(matrix).encode("utf-8")
        sessions = all((ROOT / SESSIONS_DIR / f"{r}.json").read_bytes() == dump(session_file(r, s)).encode("utf-8") for r, s in matrix["runs"].items() if s["mode"] == "shadow")
        print(json.dumps(dict(matrix_identical=same, shadow_session_files_identical=sessions), indent=1))
        return 0 if same and sessions else 1
    (ROOT / SESSIONS_DIR).mkdir(parents=True, exist_ok=True)
    with (ROOT / MATRIX).open("xb") as stream:
        stream.write(dump(matrix).encode("utf-8"))
    for run_id, spec in matrix["runs"].items():
        if spec["mode"] == "shadow":
            with (ROOT / SESSIONS_DIR / f"{run_id}.json").open("xb") as stream:
                stream.write(dump(session_file(run_id, spec)).encode("utf-8"))
    print(json.dumps(dict(written=MATRIX, runs=len(matrix["runs"]), shadow_sessions=sum(s["mode"] == "shadow" for s in matrix["runs"].values())), indent=1))
    return 0


if __name__ == "__main__":
    sys.exit(main())
